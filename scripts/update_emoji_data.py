#!/usr/bin/env python3
"""Regenerate lazygerrit/emoji_data.py from iamcal/emoji-data, the emoji names Slack uses.

python3 scripts/update_emoji_data.py [emoji.json [LICENSE]]   (paths or URLs; default: GitHub)
"""

from __future__ import annotations

import json
import sys
import urllib.request
from pathlib import Path

URL = "https://raw.githubusercontent.com/iamcal/emoji-data/master/emoji.json"
LICENSE_URL = "https://raw.githubusercontent.com/iamcal/emoji-data/master/LICENSE"
OUT = Path(__file__).resolve().parent.parent / "lazygerrit" / "emoji_data.py"
TONES = {"1F3FB", "1F3FC", "1F3FD", "1F3FE", "1F3FF"}


def read(src: str) -> str:
    if src.startswith(("http://", "https://")):
        with urllib.request.urlopen(src, timeout=60) as resp:
            return resp.read().decode("utf-8")
    return Path(src).read_text(encoding="utf-8")


def with_tone(unified: str, tone: str) -> str:
    """Where a skin tone goes: after the first code point, replacing a variation selector there."""
    first, *rest = unified.split("-")
    if rest and rest[0] == "FE0F":
        rest = rest[1:]
    return "-".join([first, tone, *rest])


def main(argv: list[str]) -> int:
    entries = json.loads(read(argv[1] if len(argv) > 1 else URL))
    license_text = read(argv[2] if len(argv) > 2 else LICENSE_URL).strip()
    rows = []
    for e in sorted(entries, key=lambda e: e.get("sort_order", 1 << 30)):
        variations = {k: v["unified"] for k, v in (e.get("skin_variations") or {}).items() if "-" not in k}
        tones = set(variations) == TONES and all(with_tone(e["unified"], k) == v for k, v in variations.items())
        rows.append(f"{e['unified']}\t{' '.join(e['short_names'])}" + ("\tt" if tones else ""))
    header = (
        '"""Slack\'s emoji names, generated by scripts/update_emoji_data.py from iamcal/emoji-data\n'
        "(https://github.com/iamcal/emoji-data). Do not edit.\n\n" + license_text + '\n"""\n\n'
        '# One emoji per line, in Slack\'s picker order: its code points, its names, and "t" if it takes\n'
        "# a skin tone (inserted after the first code point).\n"
    )
    OUT.write_text(header + 'DATA = """\\\n' + "\n".join(rows) + '\n"""\n', encoding="utf-8")
    print(f"Wrote {len(rows)} emoji to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
